"""Generates crates/caruspex-vehicles/src/generated/engines.rs from data/engines/engines.csv.

One row per model generation of the vehicle catalog (brand, model and
generation exactly as in data/vehicles/), with the engine codes the
technical data tables of its Wikipedia article name, split into petrol and
diesel. The data is under CC BY-SA 4.0 like Wikipedia (data/engines/LICENSE),
the source column names article and revision.

    py -I tools/gen_engines.py

Checked: every row names a generation of the catalog, a generation appears
once, codes are made of letters, digits and '-' only, and no code is listed
as petrol and diesel at once.
"""

from __future__ import annotations

import csv
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "engines", "engines.csv")
VEHICLES = os.path.join(ROOT, "data", "vehicles")
TARGET = os.path.join(ROOT, "crates", "caruspex-vehicles", "src", "generated", "engines.rs")
COLUMNS = ["brand", "model", "generation", "petrol", "diesel", "source"]
CODE = re.compile(r"^[A-Za-z0-9ÄÖÜäöü-]+$")


class DataError(Exception):
    pass


def rust(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def catalog() -> set[tuple[str, str, str]]:
    out = set()
    for name in sorted(os.listdir(VEHICLES)):
        if not name.endswith(".csv") or name == "brands.csv":
            continue
        with io.open(os.path.join(VEHICLES, name), encoding="utf-8") as f:
            lines = [line for line in f if line.strip() and not line.startswith("#")]
        for row in csv.DictReader(lines):
            out.add((row["brand"], row["model"], row["generation"]))
    return out


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    known = catalog()
    rows = []
    try:
        with io.open(DATA, encoding="utf-8") as f:
            lines = [line for line in f if line.strip() and not line.startswith("#")]
        reader = csv.reader(lines)
        if next(reader) != COLUMNS:
            raise DataError(f"header must be {','.join(COLUMNS)}")
        seen = set()
        for number, cells in enumerate(reader, start=2):
            if len(cells) != len(COLUMNS):
                raise DataError(f"row {number}: expected {len(COLUMNS)} columns")
            r = dict(zip(COLUMNS, (c.strip() for c in cells)))
            key = (r["brand"], r["model"], r["generation"])
            if key not in known:
                raise DataError(f"row {number}: {' '.join(key)} is not in the vehicle catalog")
            if key in seen:
                raise DataError(f"row {number}: {' '.join(key)} twice")
            seen.add(key)
            petrol, diesel = r["petrol"].split(), r["diesel"].split()
            if not petrol and not diesel:
                raise DataError(f"row {number}: no engine code")
            for code in petrol + diesel:
                if not CODE.match(code):
                    raise DataError(f"row {number}: odd engine code '{code}'")
            both = set(petrol) & set(diesel)
            if both:
                raise DataError(f"row {number}: {', '.join(sorted(both))} as petrol and diesel")
            if not r["source"].startswith("https://"):
                raise DataError(f"row {number}: the source must be the article URL")
            rows.append((key, petrol, diesel, r["source"]))
    except (DataError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    def codes(items: list[str]) -> str:
        return "&[" + ", ".join(rust(c) for c in items) + "]"

    out = [
        "// Generated by tools/gen_engines.py from data/engines/engines.csv, do not edit by hand.",
        "// Engine codes from Wikipedia, CC BY-SA 4.0 (see data/engines/LICENSE).",
        f"// {len(rows)} generations, {sum(len(p) + len(d) for _, p, d, _ in rows)} engine codes.",
        "",
        "use crate::engines::EngineRow;",
        "",
        "pub static ENGINES: &[EngineRow] = &[",
    ]
    for (brand, model, generation), petrol, diesel, source in rows:
        out.append(f"    EngineRow {{ brand: {rust(brand)}, model: {rust(model)}, generation: {rust(generation)}, "
                   f"petrol: {codes(petrol)}, diesel: {codes(diesel)}, source: {rust(source)} }},")
    out += ["];", ""]
    with io.open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(TARGET)
    print(f"{len(rows)} generations with engine codes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
