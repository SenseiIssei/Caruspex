"""Builds the translations from translations/<code>/*.json.

    py -I tools/gen_i18n.py            check, write the catalog and fill the .ts files
    py -I tools/gen_i18n.py --check    only check and report
    py -I tools/gen_i18n.py --check --strict   and fail when any text is missing or refused (CI)

Input: translations/source/ (from tools/i18n_extract.py) and, per language,
translations/<code>/core_NN.json and ui_NN.json, each {"id": "text"} (a list
of forms for plural interface texts).

Output:
  src/core/Catalog.gen.cpp       the core catalog, English text -> translation
  translations/caruspex_<code>.ts  the interface translations (the files must
                                 exist; cmake --build build --target
                                 update_translations creates them)

A translation is refused if it loses or adds a placeholder (%1 .. %9, %n),
changes the number of line breaks, is empty, or contains a long dash.
"""

from __future__ import annotations

import glob
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "translations", "source")
TARGET = os.path.join(ROOT, "src", "core", "Catalog.gen.cpp")

# Code -> number of plural forms Qt expects in the .ts file.
LANGUAGES = {
    "es": 2, "fr": 2, "pt": 2, "it": 2, "nl": 2, "pl": 3, "cs": 3, "ru": 3, "uk": 3, "tr": 1,
    "ar": 6, "zh": 1, "ja": 1, "ko": 1, "hi": 2, "id": 1,
}

PLACEHOLDER = re.compile(r"%(?:L?[1-9]|n)")
DASHES = ("—", "–")


def load_source(prefix: str) -> dict[str, dict]:
    out = {}
    for path in sorted(glob.glob(os.path.join(SOURCE, prefix + "_*.json"))):
        for item in json.load(open(path, encoding="utf-8")):
            out[item["id"]] = item
    return out


def load_language(code: str, prefix: str) -> dict:
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "translations", code, prefix + "_*.json"))):
        try:
            out.update(json.load(open(path, encoding="utf-8")))
        except json.JSONDecodeError as e:
            print(f"  {code}: {os.path.basename(path)} is not valid JSON: {e}")
    return out


def problems(original: str, text: str) -> str | None:
    if not isinstance(text, str) or not text.strip():
        return "empty"
    if sorted(PLACEHOLDER.findall(original)) != sorted(PLACEHOLDER.findall(text)):
        return "placeholders differ"
    if original.count("\n") != text.count("\n"):
        return "line breaks differ"
    if any(d in text for d in DASHES):
        return "long dash"
    return None


def cpp(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    # A hex escape must not swallow a following hex digit.
    return '"' + "".join(out) + '"'


def check_core(code: str, core_src: dict) -> tuple[dict, int, list[str]]:
    given = load_language(code, "core")
    good, bad = {}, []
    for id_, text in given.items():
        src = core_src.get(id_)
        if not src:
            continue
        why = problems(src["en"], text)
        if why:
            bad.append(f"{id_}: {why}")
        else:
            good[src["en"]] = text
    return good, len(core_src), bad


def check_ui(code: str, ui_src: dict, forms: int) -> tuple[dict, int, list[str]]:
    given = load_language(code, "ui")
    good, bad = {}, []
    for id_, text in given.items():
        src = ui_src.get(id_)
        if not src:
            continue
        key = (src["context"], src["de"])
        if src["plural"]:
            if not isinstance(text, list) or len(text) != forms:
                bad.append(f"{id_}: needs {forms} plural forms")
                continue
            why = next((p for p in (problems(src["de"], t) for t in text) if p), None)
            # Plural forms may drop %n in a form for exactly one (e.g. "ein Wert").
            if why == "placeholders differ":
                why = None
            if why:
                bad.append(f"{id_}: {why}")
                continue
            good[key] = text
        else:
            why = problems(src["de"], text)
            if why:
                bad.append(f"{id_}: {why}")
                continue
            good[key] = text
    return good, len(ui_src), bad


def write_catalog(catalogs: dict[str, dict]) -> None:
    lines = [
        "// Generated by tools/gen_i18n.py from translations/<code>/core_*.json. Do not edit by hand.",
        "",
        "#include <cstddef>",
        "#include <cstring>",
        "",
        "namespace caruspex::i18n::detail {",
        "",
        "struct CatalogEntry {",
        "    const char* en;",
        "    const char* text;",
        "};",
        "",
        "namespace {",
        "",
    ]
    for code, entries in sorted(catalogs.items()):
        lines.append(f"const CatalogEntry k_{code}[] = {{")
        for en, text in sorted(entries.items()):
            lines.append(f"    {{{cpp(en)}, {cpp(text)}}},")
        if not entries:
            lines.append("    {nullptr, nullptr},")
        lines.append("};")
        lines.append("")
    lines += ["}  // namespace", "",
              "const CatalogEntry* catalog(const char* code, std::size_t& count) {",
              "    count = 0;"]
    for code, entries in sorted(catalogs.items()):
        lines.append(f'    if (std::strcmp(code, "{code}") == 0) {{')
        lines.append(f"        count = {len(entries)};")
        lines.append(f"        return k_{code};")
        lines.append("    }")
    lines += ["    return nullptr;", "}", "", "}  // namespace caruspex::i18n::detail", ""]
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def esc(text: str) -> str:
    return html.escape(text, quote=False).replace('"', "&quot;").replace("'", "&apos;")


def fill_ts(code: str, good: dict, forms: int) -> int:
    path = os.path.join(ROOT, "translations", f"caruspex_{code}.ts")
    if not os.path.exists(path):
        return -1
    text = open(path, encoding="utf-8").read()
    filled = 0

    def ctx_sub(cm):
        nonlocal filled
        ctx = cm.group(0)
        name = html.unescape(re.search(r"<name>(.*?)</name>", ctx, re.S).group(1))

        def msg_sub(mm):
            nonlocal filled
            block = mm.group(0)
            source = html.unescape(re.search(r"<source>(.*?)</source>", block, re.S).group(1))
            value = good.get((name, source))
            if value is None:
                return block
            filled += 1
            if isinstance(value, list):
                inner = "".join(f"\n            <numerusform>{esc(v)}</numerusform>" for v in value)
                new = f"<translation>{inner}\n        </translation>"
            else:
                new = f"<translation>{esc(value)}</translation>"
            return re.sub(r"<translation[^>]*>.*?</translation>|<translation[^>]*/>", lambda _: new, block,
                          count=1, flags=re.S)

        return re.sub(r"<message[^>]*>.*?</message>", msg_sub, ctx, flags=re.S)

    text = re.sub(r"<context>.*?</context>", ctx_sub, text, flags=re.S)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return filled


def main() -> int:
    check_only = "--check" in sys.argv
    strict = "--strict" in sys.argv
    incomplete = []
    core_src = load_source("core")
    ui_src = load_source("ui")
    catalogs = {}
    failed = False
    for code, forms in LANGUAGES.items():
        core, core_total, core_bad = check_core(code, core_src)
        ui, ui_total, ui_bad = check_ui(code, ui_src, forms)
        catalogs[code] = core
        print(f"{code}: core {len(core)}/{core_total}, ui {len(ui)}/{ui_total}"
              + (f", {len(core_bad) + len(ui_bad)} refused" if core_bad or ui_bad else ""))
        for line in (core_bad + ui_bad)[:8]:
            print("    " + line)
        if len(core) < core_total or len(ui) < ui_total:
            incomplete.append(code)
        if not check_only:
            n = fill_ts(code, ui, forms)
            if n < 0:
                print(f"    caruspex_{code}.ts missing, run the update_translations target first")
                failed = True
    if not check_only:
        write_catalog(catalogs)
    if strict and incomplete:
        print("Missing translations in: " + ", ".join(incomplete) +
              ". Run tools/i18n_extract.py, translate the new ids (translations/TRANSLATING.md), "
              "then tools/gen_i18n.py.")
        return 1
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
