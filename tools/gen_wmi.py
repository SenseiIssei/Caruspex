"""Generates crates/caruspex-vehicles/src/generated/wmi_cc_by_sa.rs from data/wmi/wmi.csv.

The world manufacturer identifiers in crates/caruspex-vehicles/src/vin.rs are
checked against public domain and CC0 sources (NHTSA vPIC, Wikidata). The
codes those sources do not have follow the WMI list on Wikibooks, which is
under CC BY-SA 4.0, so they live apart in data/wmi/ with that licence and
reach the program through this generated file, which vin.rs includes as the
table WMI_CC_BY_SA.

    wmi,manufacturer,brands,year_rule,code_rule,country

    wmi           three characters (no I, O or Q)
    manufacturer  the maker as Caruspex shows it
    brands        brand names separated by |, as in the vehicle catalog
    year_rule     STD, UNK or NO_YEAR (see VinYearRule)
    code_rule     NO_CODE, VAG, MB, POR or TESLA (see VinModelCodeRule)
    country       NO_COUNTRY or one of the IN_ constants of vin.rs

Lines starting with '#' are comments.

    py -I tools/gen_wmi.py
"""

from __future__ import annotations

import csv
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(HERE, "data", "wmi", "wmi.csv")
VIN_RS = os.path.join(HERE, "crates", "caruspex-vehicles", "src", "vin.rs")
RUST_TARGET = os.path.join(HERE, "crates", "caruspex-vehicles", "src", "generated", "wmi_cc_by_sa.rs")

COLUMNS = ["wmi", "manufacturer", "brands", "year_rule", "code_rule", "country"]
YEAR_RULES = ("STD", "UNK", "NO_YEAR")
CODE_RULES = ("NO_CODE", "VAG", "MB", "POR", "TESLA")
WMI = re.compile(r"^[A-HJ-NPR-Z0-9]{3}$")


class DataError(Exception):
    pass


def countries() -> set[str]:
    """The country constants vin.rs defines (IN_GERMANY, ...)."""
    text = io.open(VIN_RS, encoding="utf-8").read()
    return set(re.findall(r"^const (IN_[A-Z_]+|NO_COUNTRY): Text", text, re.MULTILINE))


def main_table_codes() -> set[str]:
    text = io.open(VIN_RS, encoding="utf-8").read()
    return set(re.findall(r'^\s*w\("([A-Z0-9]{2,3})",', text, re.MULTILINE))


def check_text(text: str, where: str) -> None:
    for bad in (chr(0x2014), chr(0x2013)):  # em dash, en dash
        if bad in text:
            raise DataError(f"{where}: no long dashes")
    if '"' in text or "\\" in text:
        raise DataError(f"{where}: quotes and backslashes are not allowed")


def load() -> list[dict]:
    known_countries = countries()
    taken = main_table_codes()
    lines = [line for line in io.open(SOURCE, encoding="utf-8-sig")
             if line.strip() and not line.startswith("#")]
    reader = csv.DictReader(lines)
    if reader.fieldnames != COLUMNS:
        raise DataError(f"{SOURCE}: header must be {','.join(COLUMNS)}")
    rows: list[dict] = []
    seen: set[str] = set()
    for n, r in enumerate(reader, start=1):
        where = f"wmi.csv row {n} ({r.get('wmi')})"
        if not WMI.match(r["wmi"]):
            raise DataError(f"{where}: not a three character WMI")
        if r["wmi"] in seen:
            raise DataError(f"{where}: listed twice")
        if r["wmi"] in taken:
            raise DataError(f"{where}: already in the table of vin.rs")
        seen.add(r["wmi"])
        for col in ("manufacturer", "brands"):
            if not r[col]:
                raise DataError(f"{where}: {col} is empty")
            check_text(r[col], f"{where} {col}")
        if r["year_rule"] not in YEAR_RULES:
            raise DataError(f"{where}: year_rule must be one of {', '.join(YEAR_RULES)}")
        if r["code_rule"] not in CODE_RULES:
            raise DataError(f"{where}: code_rule must be one of {', '.join(CODE_RULES)}")
        if r["country"] not in known_countries:
            raise DataError(f"{where}: unknown country constant {r['country']}")
        rows.append(r)
    return rows


def write_rust(rows: list[dict]) -> None:
    lines = [
        "// Generated by tools/gen_wmi.py from data/wmi/wmi.csv, do not edit by hand.",
        "// World manufacturer identifiers after the WMI list on Wikibooks, CC BY-SA 4.0",
        "// (see data/wmi/LICENSE); included by vin.rs as WMI_CC_BY_SA.",
        f"// {len(rows)} codes.",
        "[",
    ]
    for r in rows:
        lines.append(f'    w("{r["wmi"]}", "{r["manufacturer"]}", "{r["brands"]}", {r["year_rule"]}, '
                     f'{r["code_rule"]}, {r["country"]}),')
    lines += ["]", ""]
    os.makedirs(os.path.dirname(RUST_TARGET), exist_ok=True)
    io.open(RUST_TARGET, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(RUST_TARGET)


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    try:
        rows = load()
    except DataError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    write_rust(rows)
    print(f"{len(rows)} WMI codes under CC BY-SA 4.0")
    return 0


if __name__ == "__main__":
    sys.exit(main())
